const field = (label: string, name: string, widget = 'string') => ({ label, name, widget, required: false });

const list = (label: string, label_singular: string, name: string, fields: object[]) => ({
  label,
  label_singular,
  name,
  widget: 'list',
  required: false,
  // `readonly` is ignored by the list widget, so lock structure changes explicitly.
  allow_add: false,
  allow_remove: false,
  allow_reorder: false,
  fields,
});

const readonlyFields = (fields: object[]): object[] =>
  fields.map((item) => {
    const entry = item as { fields?: object[] };
    return { ...entry, readonly: true, ...(entry.fields && { fields: readonlyFields(entry.fields) }) };
  });

